// views/RelatoriosView.tsx
import React, { useState, useMemo } from 'react';
import { Billing, Customer, DebtPayment, Expense } from '../types';
import PageHeader from '../components/PageHeader';
import { PrinterIcon } from '../components/icons/PrinterIcon';

interface RelatoriosViewProps {
  customers: Customer[];
  billings: Billing[];
  expenses: Expense[];
  debtPayments: DebtPayment[];
}

// --- Sub-components (moved outside for performance and best practices) ---

interface InfoCardProps {
    title: string;
    children: React.ReactNode;
}
const InfoCard: React.FC<InfoCardProps> = ({ title, children }) => (
    <div className="bg-slate-800 p-6 rounded-lg shadow-lg border border-slate-700 h-full">
        <h3 className="text-xl font-semibold text-white mb-4 border-b border-slate-700 pb-3">{title}</h3>
        <dl className="space-y-3">
            {children}
        </dl>
    </div>
);

interface InfoRowProps {
    label: string;
    value: string;
    valueColor?: string;
}
const InfoRow: React.FC<InfoRowProps> = ({ label, value, valueColor = 'text-slate-300' }) => (
    <div className="flex justify-between items-baseline">
        <dt className="text-slate-400">{label}</dt>
        <dd className={`font-mono font-bold ${valueColor}`}>{value}</dd>
    </div>
);

// --- Main View Component ---

const RelatoriosView: React.FC<RelatoriosViewProps> = ({ customers, billings, expenses, debtPayments }) => {
  const [currentDate, setCurrentDate] = useState(new Date());

  const handleMonthChange = (month: number) => {
    setCurrentDate(new Date(currentDate.getFullYear(), month, 1));
  };

  const handleYearChange = (year: number) => {
    setCurrentDate(new Date(year, currentDate.getMonth(), 1));
  };

  const stats = useMemo(() => {
    const year = currentDate.getFullYear();
    const month = currentDate.getMonth();

    const monthlyBillings = billings.filter(b => {
      const date = new Date(b.settledAt);
      return date.getFullYear() === year && date.getMonth() === month;
    });

    const monthlyDebtPayments = debtPayments.filter(p => {
      const date = new Date(p.paidAt);
      return date.getFullYear() === year && date.getMonth() === month;
    });

    const monthlyExpenses = expenses.filter(e => {
      const date = new Date(e.date);
      return date.getFullYear() === year && date.getMonth() === month;
    });
    
    // Revenue by Equipment
    const revenueMesa = monthlyBillings.filter(b => b.equipment === 'mesa' && b.paymentMethod !== 'fiado').reduce((sum, b) => sum + b.valorTotal, 0);
    const revenueJukebox = monthlyBillings.filter(b => b.equipment === 'jukebox' && b.paymentMethod !== 'fiado').reduce((sum, b) => sum + b.valorTotal, 0);

    // Debt Generated by Equipment
    const debtGeneratedMesa = monthlyBillings.filter(b => b.equipment === 'mesa' && b.paymentMethod === 'fiado').reduce((sum, b) => sum + b.valorTotal, 0);
    const debtGeneratedJukebox = monthlyBillings.filter(b => b.equipment === 'jukebox' && b.paymentMethod === 'fiado').reduce((sum, b) => sum + b.valorTotal, 0);
    
    // Revenue by Payment Method
    const totalRevenuePix = monthlyBillings.filter(b => b.paymentMethod === 'pix').reduce((sum, b) => sum + b.valorTotal, 0) + monthlyDebtPayments.filter(p => p.paymentMethod === 'pix').reduce((sum, p) => sum + p.amountPaid, 0);
    const totalRevenueDinheiro = monthlyBillings.filter(b => b.paymentMethod === 'dinheiro').reduce((sum, b) => sum + b.valorTotal, 0) + monthlyDebtPayments.filter(p => p.paymentMethod === 'dinheiro').reduce((sum, p) => sum + p.amountPaid, 0);

    const totalRevenue = totalRevenuePix + totalRevenueDinheiro;
    const totalExpenses = monthlyExpenses.reduce((sum, e) => sum + e.amount, 0);
    const netProfit = totalRevenue - totalExpenses;
    
    const totalDebt = customers.reduce((sum, c) => sum + c.debtAmount, 0);
    const debtorCustomers = customers.filter(c => c.debtAmount > 0).sort((a,b) => b.debtAmount - a.debtAmount);

    return {
      totalRevenue,
      totalExpenses,
      netProfit,
      totalDebt,
      revenueMesa,
      revenueJukebox,
      debtGeneratedMesa,
      debtGeneratedJukebox,
      totalRevenuePix,
      totalRevenueDinheiro,
      monthlyBillings,
      monthlyDebtPayments,
      monthlyExpenses,
      debtorCustomers
    };
  }, [billings, expenses, debtPayments, customers, currentDate]);

  const monthNames = ["Janeiro", "Fevereiro", "Março", "Abril", "Maio", "Junho", "Julho", "Agosto", "Setembro", "Outubro", "Novembro", "Dezembro"];
  const currentYear = new Date().getFullYear();
  const years = Array.from({ length: 5 }, (_, i) => currentYear - i);
  
  const handlePrintDebtors = () => {
    const itemsByCustomer = (customerId: string) => {
        const debtItems = billings
            .filter(b => b.customerId === customerId && b.paymentMethod === 'fiado')
            .map(b => b.equipment === 'mesa' ? 'M. Sinuca' : 'Jukebox');
        return [...new Set(debtItems)].join(', ');
    };
    const reportHtml = `
      <html>
        <head>
          <title>Lista de Clientes Devedores</title>
          <style>
            body { font-family: Arial, sans-serif; font-size: 10pt; color: #333; }
            @page { size: A4; margin: 20mm; }
            h1 { text-align: center; font-size: 16pt; margin-bottom: 20px; }
            table { width: 100%; border-collapse: collapse; }
            th, td { border: 1px solid #ccc; padding: 6px; text-align: left; }
            th { background-color: #f2f2f2; font-weight: bold; }
            .currency { text-align: right; font-family: monospace; }
            .total-row td { font-weight: bold; border-top: 2px solid #333; }
          </style>
        </head>
        <body>
          <h1>Lista de Clientes Devedores (Fiado)</h1>
          <table>
            <thead>
              <tr>
                <th>Cliente</th>
                <th>Cidade</th>
                <th>Itens (Origem da Dívida)</th>
                <th class="currency">Valor da Dívida</th>
              </tr>
            </thead>
            <tbody>
              ${stats.debtorCustomers.map(c => `
                <tr>
                  <td>${c.name}</td>
                  <td>${c.cidade}</td>
                  <td>${itemsByCustomer(c.id) || 'N/A'}</td>
                  <td class="currency">R$ ${c.debtAmount.toFixed(2)}</td>
                </tr>
              `).join('')}
              <tr class="total-row">
                <td colspan="3"><strong>TOTAL GERAL DE DÍVIDAS</strong></td>
                <td class="currency"><strong>R$ ${stats.totalDebt.toFixed(2)}</strong></td>
              </tr>
            </tbody>
          </table>
        </body>
      </html>
    `;
    const printWindow = window.open('', '', 'height=800,width=1000');
    if (printWindow) {
        printWindow.document.write(reportHtml);
        printWindow.document.close();
        printWindow.focus();
        printWindow.print();
        printWindow.close();
    }
  };

  const handlePrintFinancialReport = () => {
    const reportHtml = `
      <html>
        <head>
          <title>Relatório Financeiro - ${monthNames[currentDate.getMonth()]}/${currentDate.getFullYear()}</title>
          <style>
            body { font-family: Arial, sans-serif; font-size: 10pt; color: #333; }
            @page { size: A4; margin: 20mm; }
            h1, h2 { text-align: center; }
            h1 { font-size: 16pt; }
            h2 { font-size: 12pt; margin-bottom: 20px; border-bottom: 1px solid #ccc; padding-bottom: 5px; }
            h3 { font-size: 11pt; margin-top: 25px; margin-bottom: 10px; border-bottom: 1px solid #eee; padding-bottom: 3px; }
            table { width: 100%; border-collapse: collapse; margin-bottom: 20px; }
            th, td { border: 1px solid #ccc; padding: 5px; text-align: left; }
            th { background-color: #f2f2f2; font-weight: bold; }
            .summary-table td { font-size: 11pt; border: none; padding: 4px; }
            .summary-table .label { font-weight: bold; }
            .summary-table .value { text-align: right; font-family: monospace; }
            .profit { color: green; }
            .loss { color: red; }
            .details-table .currency { text-align: right; font-family: monospace; }
            .no-records { text-align: center; color: #777; font-style: italic; }
          </style>
        </head>
        <body>
          <h1>Montanha Bilhar & Jukebox</h1>
          <h2>Relatório Financeiro - ${monthNames[currentDate.getMonth()]} de ${currentDate.getFullYear()}</h2>
          
          <h3>Resumo Financeiro</h3>
          <table class="summary-table">
            <tr><td class="label">Recebido em Dinheiro:</td><td class="value">R$ ${stats.totalRevenueDinheiro.toFixed(2)}</td></tr>
            <tr><td class="label">Recebido em PIX:</td><td class="value">R$ ${stats.totalRevenuePix.toFixed(2)}</td></tr>
            <tr><td class="label"><strong>Total de Receitas (Caixa):</strong></td><td class="value"><strong>R$ ${stats.totalRevenue.toFixed(2)}</strong></td></tr>
            <tr><td class="label">Total de Despesas:</td><td class="value">R$ ${stats.totalExpenses.toFixed(2)}</td></tr>
            <tr><td class="label" style="border-top: 1px solid #ccc; padding-top: 8px;"><strong>Lucro Líquido:</strong></td><td class="value ${stats.netProfit >= 0 ? 'profit' : 'loss'}" style="border-top: 1px solid #ccc; padding-top: 8px;"><strong>R$ ${stats.netProfit.toFixed(2)}</strong></td></tr>
            <tr><td class="label">Débito Gerado (Mesa):</td><td class="value">R$ ${stats.debtGeneratedMesa.toFixed(2)}</td></tr>
            <tr><td class="label">Débito Gerado (Jukebox):</td><td class="value">R$ ${stats.debtGeneratedJukebox.toFixed(2)}</td></tr>
          </table>

          <h3>Receitas - Mesas de Sinuca</h3>
          <table class="details-table">
            <thead><tr><th>Data</th><th>Cliente</th><th>Pgto</th><th class="currency">Valor</th></tr></thead>
            <tbody>
              ${stats.monthlyBillings.filter(b => b.equipment === 'mesa').map(b => `
                <tr>
                  <td>${new Date(b.settledAt).toLocaleDateString('pt-BR')}</td>
                  <td>${b.customerName}</td>
                  <td>${b.paymentMethod}</td>
                  <td class="currency">R$ ${b.valorTotal.toFixed(2)}</td>
                </tr>
              `).join('') || '<tr><td colspan="4" class="no-records">Nenhuma cobrança de mesa no período.</td></tr>'}
            </tbody>
          </table>
          
          <h3>Receitas - Jukebox</h3>
          <table class="details-table">
            <thead><tr><th>Data</th><th>Cliente</th><th>Pgto</th><th class="currency">Valor</th></tr></thead>
            <tbody>
              ${stats.monthlyBillings.filter(b => b.equipment === 'jukebox').map(b => `
                <tr>
                  <td>${new Date(b.settledAt).toLocaleDateString('pt-BR')}</td>
                  <td>${b.customerName}</td>
                  <td>${b.paymentMethod}</td>
                  <td class="currency">R$ ${b.valorTotal.toFixed(2)}</td>
                </tr>
              `).join('') || '<tr><td colspan="4" class="no-records">Nenhuma cobrança de jukebox no período.</td></tr>'}
            </tbody>
          </table>

          <h3>Receitas - Pagamentos de Dívidas</h3>
          <table class="details-table">
            <thead><tr><th>Data</th><th>Cliente</th><th>Pgto</th><th class="currency">Valor</th></tr></thead>
            <tbody>
              ${stats.monthlyDebtPayments.map(p => `
                <tr>
                  <td>${new Date(p.paidAt).toLocaleDateString('pt-BR')}</td>
                  <td>${p.customerName}</td>
                  <td>${p.paymentMethod}</td>
                  <td class="currency">R$ ${p.amountPaid.toFixed(2)}</td>
                </tr>
              `).join('') || '<tr><td colspan="4" class="no-records">Nenhum pagamento de dívida no período.</td></tr>'}
            </tbody>
          </table>

          <h3>Detalhes das Despesas</h3>
          <table class="details-table">
            <thead><tr><th>Data</th><th>Descrição</th><th class="currency">Valor</th></tr></thead>
            <tbody>
              ${stats.monthlyExpenses.map(e => `
                <tr>
                  <td>${new Date(e.date).toLocaleDateString('pt-BR')}</td>
                  <td>${e.description}</td>
                  <td class="currency">R$ ${e.amount.toFixed(2)}</td>
                </tr>
              `).join('') || '<tr><td colspan="3" class="no-records">Nenhuma despesa registrada no período.</td></tr>'}
            </tbody>
          </table>
        </body>
      </html>
    `;
    const printWindow = window.open('', '', 'height=800,width=1000');
    if (printWindow) {
        printWindow.document.write(reportHtml);
        printWindow.document.close();
        printWindow.focus();
        printWindow.print();
        printWindow.close();
    }
  };

  return (
    <div className="max-w-6xl mx-auto">
      <div className="flex justify-between items-start mb-8">
        <PageHeader 
          title="Relatórios"
          subtitle="Análise detalhada do desempenho financeiro e controle de dívidas."
        />
        <div className="flex gap-2">
            <button 
              onClick={handlePrintFinancialReport}
              className="inline-flex items-center gap-2 bg-cyan-600 text-white font-bold py-2 px-4 rounded-md hover:bg-cyan-500 transition-colors mt-2"
            >
              <PrinterIcon className="w-5 h-5" />
              <span>Imprimir Relatório</span>
            </button>
        </div>
      </div>
      
      <div className="bg-slate-800 p-4 rounded-lg shadow-lg border border-slate-700 mb-8 flex flex-wrap items-center gap-4">
        <h3 className="text-lg font-semibold text-white">Selecione o Período:</h3>
        <select value={currentDate.getMonth()} onChange={(e) => handleMonthChange(parseInt(e.target.value))} className="bg-slate-700 border border-slate-600 rounded-md py-2 px-3 text-white focus:outline-none focus:ring-2 focus:ring-emerald-500">
          {monthNames.map((month, index) => <option key={month} value={index}>{month}</option>)}
        </select>
        <select value={currentDate.getFullYear()} onChange={(e) => handleYearChange(parseInt(e.target.value))} className="bg-slate-700 border border-slate-600 rounded-md py-2 px-3 text-white focus:outline-none focus:ring-2 focus:ring-emerald-500">
           {years.map(year => <option key={year} value={year}>{year}</option>)}
        </select>
      </div>

      <h3 className="text-2xl font-semibold text-white mb-6">Resumo do Período</h3>
      <div className="grid grid-cols-1 lg:grid-cols-2 xl:grid-cols-4 gap-8 mb-10">
        <InfoCard title="Desempenho: Mesas de Sinuca">
            <InfoRow label="Receita (Caixa)" value={`R$ ${stats.revenueMesa.toFixed(2)}`} valueColor="text-emerald-400" />
            <InfoRow label="Débito Gerado (Fiado)" value={`R$ ${stats.debtGeneratedMesa.toFixed(2)}`} valueColor="text-amber-400" />
        </InfoCard>

        <InfoCard title="Desempenho: Jukebox">
            <InfoRow label="Receita (Caixa)" value={`R$ ${stats.revenueJukebox.toFixed(2)}`} valueColor="text-emerald-400" />
            <InfoRow label="Débito Gerado (Fiado)" value={`R$ ${stats.debtGeneratedJukebox.toFixed(2)}`} valueColor="text-amber-400" />
        </InfoCard>

        <InfoCard title="Caixa do Período">
            <InfoRow label="Recebido em Dinheiro" value={`R$ ${stats.totalRevenueDinheiro.toFixed(2)}`} valueColor="text-sky-400" />
            <InfoRow label="Recebido em PIX" value={`R$ ${stats.totalRevenuePix.toFixed(2)}`} valueColor="text-green-400" />
            <InfoRow label="Total de Despesas" value={`R$ ${stats.totalExpenses.toFixed(2)}`} valueColor="text-red-400" />
            <div className="pt-3 mt-2 border-t border-slate-700/50">
                <InfoRow 
                  label="Lucro Líquido" 
                  value={`R$ ${stats.netProfit.toFixed(2)}`} 
                  valueColor={stats.netProfit >= 0 ? 'text-green-400 text-lg' : 'text-red-400 text-lg'}
                />
            </div>
        </InfoCard>
         <InfoCard title="Dívidas (Geral)">
            <InfoRow label="Dívida Total Acumulada" value={`R$ ${stats.totalDebt.toFixed(2)}`} valueColor="text-red-400 text-lg" />
        </InfoCard>
      </div>
      
      <div className="bg-slate-800 rounded-lg shadow-lg border border-slate-700 overflow-hidden">
        <div className="flex justify-between items-center p-4 bg-slate-700/50">
            <h3 className="text-lg font-semibold text-white">Clientes Devedores (Fiado)</h3>
            <button 
                onClick={handlePrintDebtors}
                className="inline-flex items-center gap-2 bg-cyan-600 text-white font-bold py-1.5 px-3 rounded-md hover:bg-cyan-500 transition-colors text-sm"
            >
              <PrinterIcon className="w-4 h-4" />
              <span>Imprimir Lista</span>
            </button>
        </div>
        <div className="overflow-x-auto">
            <table className="w-full text-sm text-left text-slate-300 min-w-[720px]">
                <thead className="text-xs text-slate-400 uppercase bg-slate-700/50">
                    <tr>
                        <th scope="col" className="px-6 py-3">Cliente</th>
                        <th scope="col" className="px-6 py-3">Cidade</th>
                        <th scope="col" className="px-6 py-3">Itens (Origem da Dívida)</th>
                        <th scope="col" className="px-6 py-3 text-right">Valor da Dívida</th>
                    </tr>
                </thead>
                <tbody>
                    {stats.debtorCustomers.length > 0 ? stats.debtorCustomers.map(customer => {
                        const debtItems = billings
                            .filter(b => b.customerId === customer.id && b.paymentMethod === 'fiado')
                            .map(b => b.equipment === 'mesa' ? 'M. Sinuca' : 'Jukebox');
                        const uniqueItems = [...new Set(debtItems)].join(', ');

                        return (
                            <tr key={customer.id} className="bg-slate-800 border-b border-slate-700 hover:bg-slate-700/50">
                                <td className="px-6 py-4 font-medium text-white whitespace-nowrap">{customer.name}</td>
                                <td className="px-6 py-4">{customer.cidade}</td>
                                <td className="px-6 py-4">{uniqueItems || 'N/A'}</td>
                                <td className="px-6 py-4 text-right font-mono text-red-400 font-bold">R$ {customer.debtAmount.toFixed(2)}</td>
                            </tr>
                        )
                    }) : (
                        <tr>
                            <td colSpan={4} className="text-center py-16 text-slate-400 italic">Nenhum cliente com dívidas.</td>
                        </tr>
                    )}
                </tbody>
                 <tfoot className="bg-slate-700/50">
                    <tr className="font-bold text-white">
                        <td colSpan={3} className="text-right px-6 py-3 uppercase">Total Geral de Dívidas</td>
                        <td className="text-right px-6 py-3 font-mono text-lg">R$ {stats.totalDebt.toFixed(2)}</td>
                    </tr>
                </tfoot>
            </table>
        </div>
      </div>

    </div>
  );
};

export default RelatoriosView;